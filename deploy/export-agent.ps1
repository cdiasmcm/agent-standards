# Generates build files from an agent's Markdown tables (the Markdown stays the source of truth):
#   build/input.schema.json   from io/INPUT.md  "## Payload fields"
#   build/output.schema.json  from io/OUTPUT.md "## Result fields"
#   build/golden-set.jsonl    from evals/GOLDEN-SET.md (rows G001..., the EX row is skipped)
# Run at the MVP gate or whenever the tables change. Never hand-edit build/.
#   powershell -ExecutionPolicy Bypass -File deploy/export-agent.ps1 -Path <agent folder>

param([Parameter(Mandatory = $true)][string]$Path)

$ErrorActionPreference = 'Stop'
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Get-TableRows([string]$file, [string]$heading) {
    if (-not (Test-Path -LiteralPath $file)) { throw "Missing $file" }
    $lines = [System.IO.File]::ReadAllLines($file, $utf8)
    $in = $false; $rows = @()
    foreach ($l in $lines) {
        if ($heading -and $l -match "^##\s+$([regex]::Escape($heading))") { $in = $true; continue }
        if ($heading -and $in -and $l -match '^##\s') { break }
        if (($in -or -not $heading) -and $l -match '^\|') {
            # Split on unescaped pipes only; "\|" inside a cell (e.g. enum(a\|b)) is a literal pipe.
            $cells = @([regex]::Split($l.Trim().Trim('|'), '(?<!\\)\|') | ForEach-Object { $_.Trim() -replace '\\\|', '|' })
            if ($cells[0] -match '^-+$' -or $cells[0] -match '^(Field|ID)$') { continue }
            $rows += , $cells
        }
    }
    return $rows
}

function ConvertTo-SchemaType([string]$t) {
    $t = $t.Trim()
    if ($t -match '^enum\((.+)\)$') { return @{ type = 'string'; enum = @($Matches[1].Split('|') | ForEach-Object { $_.Trim() }) } }
    if ($t -match '^array<(.+)>$') { return @{ type = 'array'; items = (ConvertTo-SchemaType $Matches[1]) } }
    switch ($t) {
        'date'     { return @{ type = 'string'; format = 'date' } }
        'datetime' { return @{ type = 'string'; format = 'date-time' } }
        'string'   { return @{ type = 'string' } }
        'number'   { return @{ type = 'number' } }
        'integer'  { return @{ type = 'integer' } }
        'boolean'  { return @{ type = 'boolean' } }
        'object'   { return @{ type = 'object' } }
        default    { throw "Unknown type '$t' (use string, number, integer, boolean, date, datetime, enum(a|b), array<type>, object)" }
    }
}

function New-Schema([object[]]$rows, [string]$title) {
    $props = [ordered]@{}; $required = @()
    foreach ($r in $rows) {
        if ($r[0] -match 'TODO') { throw "$title still has TODO rows. Fill the table first" }
        $p = ConvertTo-SchemaType $r[1]
        if ($r.Count -gt 3 -and $r[3]) { $p.description = $r[3] }
        $props[$r[0]] = $p
        if ($r[2] -match '^(yes|y|true)$') { $required += $r[0] }
    }
    return [ordered]@{
        '$schema'            = 'https://json-schema.org/draft/2020-12/schema'
        title                = $title
        description          = 'GENERATED by deploy/export-agent.ps1 from Markdown. Do not edit.'
        type                 = 'object'
        properties           = $props
        required             = $required
        additionalProperties = $false
    }
}

$build = Join-Path $Path 'build'
New-Item -ItemType Directory -Force -Path $build | Out-Null

$in = New-Schema (Get-TableRows (Join-Path $Path 'io\INPUT.md') 'Payload fields') 'payload'
[System.IO.File]::WriteAllText((Join-Path $build 'input.schema.json'), ($in | ConvertTo-Json -Depth 20), $utf8)

$out = New-Schema (Get-TableRows (Join-Path $Path 'io\OUTPUT.md') 'Result fields') 'result'
[System.IO.File]::WriteAllText((Join-Path $build 'output.schema.json'), ($out | ConvertTo-Json -Depth 20), $utf8)

$golden = Get-TableRows (Join-Path $Path 'evals\GOLDEN-SET.md') $null | Where-Object { $_[0] -match '^G\d+$' }
$jsonl = @($golden | ForEach-Object {
    ([ordered]@{ id = $_[0]; input = $_[1]; expected = $_[2]; failure_mode = $_[3]; critical = ($_[4] -match '^(yes|y|true)$'); source = $_[5] } | ConvertTo-Json -Compress)
})
[System.IO.File]::WriteAllText((Join-Path $build 'golden-set.jsonl'), (($jsonl -join "`n") + "`n"), $utf8)

Write-Output "Built $build : input.schema.json ($($in.properties.Count) fields), output.schema.json ($($out.properties.Count) fields), golden-set.jsonl ($($jsonl.Count) cases)"
