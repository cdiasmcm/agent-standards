# Generates build files from an agent's Markdown (the Markdown stays the source of truth):
#   build/input.schema.json   from io/INPUT.md  "## Payload fields"
#   build/output.schema.json  from io/OUTPUT.md "## Result fields"
#   build/golden-set.jsonl    from evals/GOLDEN-SET.md (rows G001..., the EX row is skipped)
#   build/agent-card.json     A2A v1.0 Agent Card, from AGENT.md, PROMPT.md and CHANGELOG.md
# Run after Create or Adopt, at every gate, and whenever those files change. Never hand-edit build/.
# A table that still has TODO rows is skipped with a note; the Agent Card is always written.
# Python twin for tools without PowerShell: deploy/export_agent.py (keep the two in step).
#   powershell -ExecutionPolicy Bypass -File deploy/export-agent.ps1 -Path <agent folder>

param([Parameter(Mandatory = $true)][string]$Path)

$ErrorActionPreference = 'Stop'
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Read-Lines([string]$file) {
    if (Test-Path -LiteralPath $file) { return [System.IO.File]::ReadAllLines($file, $utf8) }
    return @()
}

function Get-TableRows([string]$file, [string]$heading) {
    if (-not (Test-Path -LiteralPath $file)) { throw "Missing $file" }
    $lines = [System.IO.File]::ReadAllLines($file, $utf8)
    $in = $false; $rows = @()
    foreach ($l in $lines) {
        if ($heading -and $l -match "^##\s+$([regex]::Escape($heading))") { $in = $true; continue }
        if ($heading -and $in -and $l -match '^##\s') { break }
        if (($in -or -not $heading) -and $l -match '^\|') {
            # Split on unescaped pipes only; "\|" inside a cell (e.g. enum(a\|b)) is a literal pipe.
            $cells = @([regex]::Split($l.Trim().Trim('|'), '(?<!\\)\|') | ForEach-Object { $_.Trim() -replace '\\\|', '|' })
            if ($cells[0] -match '^-+$' -or $cells[0] -match '^(Field|ID)$') { continue }
            $rows += , $cells
        }
    }
    return , $rows   # the comma keeps a one-row table from being unrolled into its cells
}

function ConvertTo-SchemaType([string]$t) {
    $t = $t.Trim()
    if ($t -match '^enum\((.+)\)$') { return @{ type = 'string'; enum = @($Matches[1].Split('|') | ForEach-Object { $_.Trim() }) } }
    if ($t -match '^array<(.+)>$') { return @{ type = 'array'; items = (ConvertTo-SchemaType $Matches[1]) } }
    switch ($t) {
        'date'     { return @{ type = 'string'; format = 'date' } }
        'datetime' { return @{ type = 'string'; format = 'date-time' } }
        'string'   { return @{ type = 'string' } }
        'number'   { return @{ type = 'number' } }
        'integer'  { return @{ type = 'integer' } }
        'boolean'  { return @{ type = 'boolean' } }
        'object'   { return @{ type = 'object' } }
        default    { throw "Unknown type '$t' (use string, number, integer, boolean, date, datetime, enum(a|b), array<type>, object)" }
    }
}

function New-Schema([object[]]$rows, [string]$title) {
    $props = [ordered]@{}; $required = @()
    foreach ($r in $rows) {
        if ($r[0] -match 'TODO') { return $null }
        $p = ConvertTo-SchemaType $r[1]
        if ($r.Count -gt 3 -and $r[3]) { $p.description = $r[3] }
        $props[$r[0]] = $p
        if ($r[2] -match '^(yes|y|true)$') { $required += $r[0] }
    }
    return [ordered]@{
        '$schema'            = 'https://json-schema.org/draft/2020-12/schema'
        title                = $title
        description          = 'GENERATED by deploy/export-agent from Markdown. Do not edit.'
        type                 = 'object'
        properties           = $props
        required             = $required
        additionalProperties = $false
    }
}

function Test-Open([string]$v) { return (-not $v) -or $v -match 'TODO' -or $v -match '^N/A' }

$build = Join-Path $Path 'build'
New-Item -ItemType Directory -Force -Path $build | Out-Null
$notes = @()

foreach ($s in @(@{ File = 'io\INPUT.md'; Heading = 'Payload fields'; Title = 'payload'; Out = 'input.schema.json' },
                 @{ File = 'io\OUTPUT.md'; Heading = 'Result fields'; Title = 'result'; Out = 'output.schema.json' })) {
    $schema = New-Schema (Get-TableRows (Join-Path $Path $s.File) $s.Heading) $s.Title
    if ($schema) { [System.IO.File]::WriteAllText((Join-Path $build $s.Out), ($schema | ConvertTo-Json -Depth 20), $utf8); $notes += "$($s.Out): $($schema.properties.Count) fields" }
    else { $notes += "$($s.Out) skipped: $($s.File) still has TODO rows" }
}

$goldenRows = Get-TableRows (Join-Path $Path 'evals\GOLDEN-SET.md') $null
$golden = @($goldenRows | Where-Object { $_[0] -match '^G\d+$' })
$jsonl = @($golden | ForEach-Object {
    ([ordered]@{ id = $_[0]; input = $_[1]; expected = $_[2]; failure_mode = $_[3]; critical = ($_[4] -match '^(yes|y|true)$'); source = $_[5] } | ConvertTo-Json -Compress)
})
[System.IO.File]::WriteAllText((Join-Path $build 'golden-set.jsonl'), (($jsonl -join "`n") + "`n"), $utf8)
$notes += "golden-set.jsonl: $($jsonl.Count) cases"

# Agent Card (A2A v1.0, https://a2a-protocol.org/latest/specification/). Always generated from the agent's
# own files so it never drifts. It describes the agent's job, never its internal tools or skills.
$agent = Read-Lines (Join-Path $Path 'AGENT.md')
$prompt = Read-Lines (Join-Path $Path 'PROMPT.md')
$changelog = Read-Lines (Join-Path $Path 'CHANGELOG.md')
$name = (($agent | Where-Object { $_ -match '^#\s+Agent:' } | Select-Object -First 1) -replace '^#\s+Agent:\s*', '').Trim()
$role = ($prompt | Where-Object { $_ -match '\*\*Role' } | Select-Object -First 1)
$description = if ($role -match '\*\*Role[^*]*\*\*[^:]*:\s*(.+)$') { $Matches[1].Trim() } else { '' }
$verLine = ($changelog | Where-Object { $_ -match '^\|\s*\d+\.\d+\.\d+\s*\|' } | Select-Object -First 1)
$version = if ($verLine -match '^\|\s*(\d+\.\d+\.\d+)') { $Matches[1] } else { '0.0.0' }
$a2a = ($agent | Where-Object { $_ -match '\*\*A2A:\*\*' } | Select-Object -First 1)
$endpoint = if ($a2a -match 'endpoint\s+(\S+)') { $Matches[1] } else { '' }
$binding = if ($a2a -match 'binding\s+(\S+)') { $Matches[1] } else { 'JSONRPC' }
$auth = if ($a2a -match 'auth\s+(\S+)') { $Matches[1] } else { '' }
$exposed = -not (Test-Open $endpoint) -and $a2a -notmatch '\*\*A2A:\*\*\s*N/A'
$slug = ($name.ToLower() -replace '[^a-z0-9]+', '-').Trim('-')
$examples = @()
if (Test-Path -LiteralPath (Join-Path $Path 'PROMPT.md')) {
    $exampleRows = Get-TableRows (Join-Path $Path 'PROMPT.md') 'Examples'
    $examples = @($exampleRows | Where-Object { $_[0] -match '^P\d+$' -and -not (Test-Open $_[1]) } | ForEach-Object { $_[1] })
}

$skill = [ordered]@{ id = $slug; name = $name; description = $description; tags = @('agent-standards') }
if ($examples.Count -gt 0) { $skill.examples = $examples }
$interfaces = @()
if ($exposed) { $interfaces += [ordered]@{ url = $endpoint; protocolBinding = $binding; protocolVersion = '1.0' } }
$card = [ordered]@{
    name                = $name
    description         = $description
    supportedInterfaces = $interfaces
    version             = $version
    capabilities        = [ordered]@{ streaming = $false; pushNotifications = $false }
    defaultInputModes   = @('application/json')
    defaultOutputModes  = @('application/json')
    skills              = @($skill)
}
[System.IO.File]::WriteAllText((Join-Path $build 'agent-card.json'), ($card | ConvertTo-Json -Depth 20), $utf8)
$notes += "agent-card.json: version $version, " + $(if ($exposed) { "exposed at $endpoint ($binding)" } else { 'internal only (not exposed via A2A)' })
if (Test-Open $name) { $notes += 'agent-card.json: name still TODO (AGENT.md heading)' }
if (Test-Open $description) { $notes += 'agent-card.json: description still TODO (PROMPT.md Role)' }
if ($exposed -and -not (Test-Open $auth)) { $notes += "agent-card.json: add the securitySchemes entry for '$auth' before publishing it at /.well-known/agent-card.json" }

Write-Output "Built $build"
$notes | ForEach-Object { Write-Output "- $_" }
