"""Audits an agent folder against the Agent Standard (STANDARD.md): checks that every one of the
8 blocks exists and that the fields required for the agent's tier and stage are filled.
This checks completeness only. The advisor does the judgment review afterwards.

Python port of deploy/audit-agent.ps1, for tools without PowerShell (e.g. Databricks Genie Code).
Keep the two in step. Standard library only, Python 3.9+.

  python audit_agent.py <agent folder> [--save | --out report.md]
    --save writes <agent folder>/reviews/standards-audit-YYYY-MM-DD.md; without --save/--out it only prints.

  In a notebook:
    from audit_agent import run_audit
    print(run_audit("/Workspace/Users/<you>/my-agent", save=True))

The framework is read-only: writing anything inside the agent-standards folder is refused.
Exit code: 0 = no block missing or empty, 1 = at least one block MISSING, NOT STARTED or BLOCKED
(task not Green Light), or a refused write; 2 = folder has no AGENT.md (not a skeleton layout: map the
8 blocks instead, see AUDIT.md).
"""

import argparse
import datetime
import os
import re
import sys

STANDARDS_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

BLOCKS = [
    (1, 'Purpose', 'AGENT.md', 1, None),
    (2, 'Steps', 'AGENT.md', 2, 'PROMPT.md'),
    (3, 'Input', 'io/INPUT.md', 0, 'knowledge/README.md'),
    (4, 'Output', 'io/OUTPUT.md', 0, None),
    (5, 'Tools & Access', 'AGENT.md', 5, None),
    (6, 'Controls', 'AGENT.md', 6, None),
    (7, 'Evals & DQ', 'evals/EVAL-PLAN.md', 0, None),
    (8, 'Operations', 'AGENT.md', 8, None),
]
MIN_GOLDEN = {'Design': 0, 'MVP': 20, 'Pilot': 100, 'Scale': 300}
TIERS = {'lite': 'Lite', 'standard': 'Standard', 'critical': 'Critical'}
STAGES = {'design': 'Design', 'mvp': 'MVP', 'pilot': 'Pilot', 'scale': 'Scale'}
# _archive/ holds originals after an Adopt and is disregarded; build/ is generated by export-agent.ps1.
SKELETON_NAMES = {n.lower() for n in ['AGENT.md', 'PROMPT.md', 'CHANGELOG.md', 'DECISIONS.md', 'STATE.md',
                                      'io', 'evals', 'knowledge', 'skills', 'reviews', '_archive', 'build']}

NOT_SKELETON = (
    "This folder has no AGENT.md, so it doesn't follow the skeleton layout yet.\n"
    "Map its existing files onto the 8 blocks instead (AUDIT.md step 3, done by your AI).\n"
    "To bring it onto the skeleton, use the Adopt workflow (AGENT-PROMPT.md): merge the existing\n"
    "files into the skeleton with the owner, never overwrite, and keep originals in _archive/."
)


def _has(pattern, line):
    # PowerShell -match is case-insensitive; keep the same behaviour.
    return re.search(pattern, line, re.IGNORECASE) is not None


def _read_lines(path):
    if not os.path.isfile(path):
        return None
    with open(path, encoding='utf-8-sig') as f:
        return f.read().splitlines()


def _section(lines, number):
    start = next((i for i, l in enumerate(lines) if _has(r'^##\s+%d\.\s' % number, l)), -1)
    if start < 0:
        return None
    end = next((j for j in range(start + 1, len(lines)) if _has(r'^##\s', lines[j])), len(lines))
    return lines[start:end]


def _applicable(line, tier):
    # [if: ...] fields always count: fill them or mark N/A (reason).
    if _has(r'\[if:', line):
        return True
    if _has(r'\[C\]', line):
        return tier == 'Critical'
    if _has(r'\[S\]', line):
        return tier in ('Standard', 'Critical')
    return _has(r'\[L\]', line)


def _measure(lines, tier):
    total, open_fields = 0, []
    for l in lines:
        if not _has(r'\[(L|S|C)\]|\[if:', l) or not _applicable(l, tier):
            continue
        total += 1
        if _has('TODO', l):
            label = re.sub(r'^\s*[-|]\s*', '', l).replace('**', '')
            label = re.sub(r'\s+', ' ', label).strip()
            if len(label) > 90:
                label = label[:90] + '...'
            open_fields.append(label)
    return total, open_fields


def _skill_issues(path, lines):
    # Every own skill listed in the section 5 skills table has skills/<name>/SKILL.md, and every folder
    # in skills/ has a SKILL.md whose name matches the folder.
    issues, in_skills = [], False
    for l in lines:
        if _has(r'^\|\s*Skill \(', l):
            in_skills = True
            continue
        if in_skills and not l.startswith('|'):
            in_skills = False
        if not in_skills:
            continue
        cells = [c.strip().strip('`') for c in l.strip().strip('|').split('|')]
        if re.match(r'^(-+|TODO|N/A.*)?$', cells[0], re.IGNORECASE):
            continue
        if len(cells) > 1 and _has(r'^own', cells[1]):
            if not os.path.isfile(os.path.join(path, 'skills', cells[0], 'SKILL.md')):
                issues.append('skills/%s/SKILL.md not found (listed as an own skill in AGENT.md section 5)' % cells[0])
    skills_dir = os.path.join(path, 'skills')
    if os.path.isdir(skills_dir):
        for d in sorted(os.listdir(skills_dir), key=str.lower):
            if not os.path.isdir(os.path.join(skills_dir, d)):
                continue
            skill = _read_lines(os.path.join(skills_dir, d, 'SKILL.md'))
            if not skill:
                issues.append('skills/%s/ has no SKILL.md' % d)
                continue
            name_line = next((l for l in skill if _has(r'^name:\s*\S', l)), None)
            if not name_line:
                issues.append('skills/%s/SKILL.md has no name in its frontmatter' % d)
                continue
            skill_name = re.sub(r'^name:\s*', '', name_line, flags=re.IGNORECASE).strip().strip('"').strip("'")
            if skill_name != d:
                issues.append("skills/%s/SKILL.md: name '%s' doesn't match the folder name" % (d, skill_name))
    return issues


def _resolve_out(path, out, save):
    if save and not out:
        out = os.path.join(path, 'reviews', 'standards-audit-%s.md' % datetime.date.today().isoformat())
    if not out:
        return None
    out = os.path.abspath(out)
    root = os.path.join(STANDARDS_ROOT, '')
    if os.path.normcase(out).startswith(os.path.normcase(root)):
        raise PermissionError(
            'REFUSED: %s is inside the agent-standards framework, which is read-only. Save audit reports '
            "in the agent's own folder (e.g. <agent>/reviews/)." % out)
    return out


def audit_folder(path):
    """Returns (report, exit_code). Writes nothing."""
    agent = _read_lines(os.path.join(path, 'AGENT.md'))
    if agent is None:
        return NOT_SKELETON, 2

    tier, stage, header_issues = 'Lite', 'Design', []
    t = next((l for l in agent if _has(r'^\*\*Tier:\*\*', l)), None)
    m = re.search(r'(Lite|Standard|Critical)', t or '', re.IGNORECASE)
    if m and not _has('TODO', t):
        tier = TIERS[m.group(1).lower()]
    else:
        header_issues.append('Tier not set (audited as Lite)')
    s = next((l for l in agent if _has(r'^\*\*Stage:\*\*', l)), None)
    m = re.search(r'\*\*Stage:\*\*\s*(Design|MVP|Pilot|Scale)', s or '', re.IGNORECASE)
    if m:
        stage = STAGES[m.group(1).lower()]

    results = []
    for n, name, rel, sec, extra_rel in BLOCKS:
        issues = []
        lines = _read_lines(os.path.join(path, rel))
        if lines and sec > 0:
            lines = _section(lines, sec)
        if not lines:
            where = '%s (section %d)' % (rel, sec) if sec > 0 else rel
            results.append((n, name, 'MISSING', '-', ['%s not found' % where]))
            continue
        total, open_fields = _measure(lines, tier)
        issues += open_fields

        # Blocks 2 and 3 have a second file: PROMPT.md (instructions) and knowledge/README.md (reference files).
        if extra_rel:
            extra = _read_lines(os.path.join(path, extra_rel))
            if not extra:
                issues.append('%s missing' % extra_rel)
            else:
                xt, xo = _measure(extra, tier)
                total += xt
                open_fields = open_fields + xo
                issues += xo
                if n == 2:
                    in_fence = after_heading = placeholder = False
                    for l in extra:
                        if _has(r'^##\s', l):
                            after_heading = _has(r'^##\s+System prompt', l)
                        if after_heading and l.startswith('```'):
                            in_fence = not in_fence
                            continue
                        if in_fence and l.strip().upper() == 'TODO':
                            placeholder = True
                    if placeholder:
                        issues.append('PROMPT.md: system prompt not written yet')
                if n == 3:
                    for l in extra:
                        if not l.startswith('|'):
                            continue
                        cell = l.strip().strip('|').split('|')[0].strip().strip('`')
                        if re.match(r'^(File|-+|TODO|N/A.*)?$', cell, re.IGNORECASE):
                            continue
                        if not os.path.exists(os.path.join(path, 'knowledge', cell)):
                            issues.append('knowledge/%s is listed in knowledge/README.md but not found' % cell)

        if n == 1:
            zone = next((l for l in lines if _has('Task selection', l)), '')
            zm = re.search(r'zone\s+(Red|Low)', zone, re.IGNORECASE)
            if zm:
                issues.insert(0, 'Task is not Green Light (zone: %s). Do not build' % zm.group(1))
            issues = header_issues + issues
        if n == 5:
            issues += _skill_issues(path, lines)
        if n == 7:
            golden = _read_lines(os.path.join(path, 'evals', 'GOLDEN-SET.md'))
            if not golden:
                issues.append('evals/GOLDEN-SET.md missing')
            else:
                count = sum(1 for l in golden if _has(r'^\|\s*G\d+\s*\|', l))
                need = MIN_GOLDEN[stage]
                if count < need:
                    issues.append('Golden set has %d real cases; stage %s needs %d' % (count, stage, need))
                elif need == 0 and count == 0:
                    issues.append('Golden set is empty (needs 20 real cases before MVP)')
        if n == 8:
            for f in ('CHANGELOG.md', 'DECISIONS.md', 'STATE.md'):
                if not os.path.exists(os.path.join(path, f)):
                    issues.append('%s missing' % f)
            state = _read_lines(os.path.join(path, 'STATE.md'))
            if state:
                resume = next((l for l in state if _has('Resume here', l)), None)
                if not resume or _has('TODO', resume):
                    issues.append('STATE.md has no "Resume here" next action')
            log = _read_lines(os.path.join(path, 'CHANGELOG.md'))
            if log and stage != 'Design':
                released = [l for l in log if _has(r'^\|\s*\d+\.\d+\.\d+', l) and _has(r'\|\s*good\s*\|', l)]
                if not released:
                    issues.append("CHANGELOG.md has no version marked 'good' with a gate (stage %s)" % stage)

        filled = '%d/%d' % (total - len(open_fields), total) if total > 0 else '0/0'
        blocked = n == 1 and any(i.startswith('Task is not Green Light') for i in issues)
        if blocked:
            status = 'BLOCKED'
        elif total > 0 and len(open_fields) == total:
            status = 'NOT STARTED'
        elif issues:
            status = 'GAPS'
        else:
            status = 'PASS'
        results.append((n, name, status, filled, issues))

    # Top-level entries that aren't part of the skeleton (info only, never fails the audit).
    extras = []
    for e in sorted(os.listdir(path), key=str.lower):
        if e.startswith('.') or e.lower() in SKELETON_NAMES:
            continue
        extras.append(e + '/' if os.path.isdir(os.path.join(path, e)) else e)

    out = ['# Agent audit: %s' % os.path.basename(os.path.abspath(path).rstrip('/\\')), '',
           'Date: %s | Tier: %s | Stage: %s | Completeness only; the judgment review follows.'
           % (datetime.date.today().isoformat(), tier, stage), '',
           '| # | Block | Status | Fields filled |', '|---|-------|--------|---------------|']
    out += ['| %d | %s | %s | %s |' % (n, name, status, filled) for n, name, status, filled, _ in results]
    for n, name, status, _, issues in results:
        if issues:
            out += ['', '## %d. %s: %s' % (n, name, status)] + ['- %s' % i for i in issues]
    if extras:
        out += ['', '## Not in the skeleton (ask the owner where these belong; see Adopt in AGENT-PROMPT.md)']
        out += ['- %s' % e for e in extras]
    report = '\n'.join(out) + '\n'
    code = 1 if any(r[2] in ('MISSING', 'NOT STARTED', 'BLOCKED') for r in results) else 0
    return report, code


def run_audit(path, save=False, out=None):
    """Notebook entry point: returns the report and saves it when asked. Never exits the interpreter."""
    target = _resolve_out(path, out, save)
    report, code = audit_folder(path)
    if target and code != 2:
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with open(target, 'w', encoding='utf-8') as f:
            f.write(report)
        report += 'Saved: %s\n' % target
    return report


def main(argv=None):
    p = argparse.ArgumentParser(description='Audit an agent folder against the Agent Standard.')
    p.add_argument('path', help='agent folder')
    p.add_argument('--out', help='write the report to this file')
    p.add_argument('--save', action='store_true', help='write <agent>/reviews/standards-audit-YYYY-MM-DD.md')
    a = p.parse_args(argv)
    try:
        target = _resolve_out(a.path, a.out, a.save)
    except PermissionError as e:
        print(e)
        return 1
    report, code = audit_folder(a.path)
    print(report)
    if target and code != 2:
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with open(target, 'w', encoding='utf-8') as f:
            f.write(report)
        print('Saved: %s' % target)
    return code


if __name__ == '__main__':
    sys.exit(main())
