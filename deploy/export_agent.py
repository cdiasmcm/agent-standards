"""Generates build files from an agent's Markdown (the Markdown stays the source of truth):
  build/input.schema.json   from io/INPUT.md  "## Payload fields"
  build/output.schema.json  from io/OUTPUT.md "## Result fields"
  build/golden-set.jsonl    from evals/GOLDEN-SET.md (rows G001..., the EX row is skipped)
  build/agent-card.json     A2A v1.0 Agent Card, from AGENT.md, PROMPT.md and CHANGELOG.md
Run after Create or Adopt, at every gate, and whenever those files change. Never hand-edit build/.
A table that still has TODO rows is skipped with a note; the Agent Card is always written.

Python twin of deploy/export-agent.ps1, for tools without PowerShell (e.g. Databricks Genie Code).
Keep the two in step. Standard library only, Python 3.9+.

  python export_agent.py <agent folder>
  In a notebook:  from export_agent import run_export; print(run_export("/Workspace/.../my-agent"))
"""

import json
import os
import re
import sys


def _lines(path):
    if not os.path.isfile(path):
        return []
    with open(path, encoding='utf-8-sig') as f:
        return f.read().splitlines()


def _table_rows(path, heading):
    if not os.path.isfile(path):
        raise FileNotFoundError('Missing %s' % path)
    rows, inside = [], False
    for l in _lines(path):
        if heading and re.match(r'^##\s+' + re.escape(heading), l, re.IGNORECASE):
            inside = True
            continue
        if heading and inside and re.match(r'^##\s', l):
            break
        if (inside or not heading) and l.startswith('|'):
            # Split on unescaped pipes only; "\|" inside a cell (e.g. enum(a\|b)) is a literal pipe.
            cells = [c.strip().replace('\\|', '|') for c in re.split(r'(?<!\\)\|', l.strip().strip('|'))]
            if re.match(r'^-+$', cells[0]) or re.match(r'^(Field|ID)$', cells[0], re.IGNORECASE):
                continue
            rows.append(cells)
    return rows


def _schema_type(t):
    t = t.strip()
    m = re.match(r'^enum\((.+)\)$', t)
    if m:
        return {'type': 'string', 'enum': [x.strip() for x in m.group(1).split('|')]}
    m = re.match(r'^array<(.+)>$', t)
    if m:
        return {'type': 'array', 'items': _schema_type(m.group(1))}
    simple = {'date': {'type': 'string', 'format': 'date'}, 'datetime': {'type': 'string', 'format': 'date-time'},
              'string': {'type': 'string'}, 'number': {'type': 'number'}, 'integer': {'type': 'integer'},
              'boolean': {'type': 'boolean'}, 'object': {'type': 'object'}}
    if t not in simple:
        raise ValueError("Unknown type '%s' (use string, number, integer, boolean, date, datetime, enum(a|b), "
                         "array<type>, object)" % t)
    return dict(simple[t])


def _schema(rows, title):
    props, required = {}, []
    for r in rows:
        if 'TODO' in r[0].upper():
            return None
        p = _schema_type(r[1])
        if len(r) > 3 and r[3]:
            p['description'] = r[3]
        props[r[0]] = p
        if re.match(r'^(yes|y|true)$', r[2], re.IGNORECASE):
            required.append(r[0])
    return {'$schema': 'https://json-schema.org/draft/2020-12/schema', 'title': title,
            'description': 'GENERATED by deploy/export-agent from Markdown. Do not edit.', 'type': 'object',
            'properties': props, 'required': required, 'additionalProperties': False}


def _open(v):
    return not v or 'TODO' in v.upper() or re.match(r'^N/A', v, re.IGNORECASE) is not None


def _first(lines, pattern):
    return next((l for l in lines if re.search(pattern, l, re.IGNORECASE)), None)


def run_export(path):
    """Writes <path>/build/ and returns a short report. Never exits the interpreter."""
    build = os.path.join(path, 'build')
    os.makedirs(build, exist_ok=True)
    notes = []

    for rel, heading, title, out in (('io/INPUT.md', 'Payload fields', 'payload', 'input.schema.json'),
                                     ('io/OUTPUT.md', 'Result fields', 'result', 'output.schema.json')):
        schema = _schema(_table_rows(os.path.join(path, rel), heading), title)
        if schema:
            with open(os.path.join(build, out), 'w', encoding='utf-8') as f:
                json.dump(schema, f, indent=2, ensure_ascii=False)
            notes.append('%s: %d fields' % (out, len(schema['properties'])))
        else:
            notes.append('%s skipped: %s still has TODO rows' % (out, rel.replace('/', '\\')))

    golden = [r for r in _table_rows(os.path.join(path, 'evals', 'GOLDEN-SET.md'), None) if re.match(r'^G\d+$', r[0])]
    with open(os.path.join(build, 'golden-set.jsonl'), 'w', encoding='utf-8', newline='\n') as f:
        for r in golden:
            r = r + [''] * (6 - len(r))
            f.write(json.dumps({'id': r[0], 'input': r[1], 'expected': r[2], 'failure_mode': r[3],
                                'critical': re.match(r'^(yes|y|true)$', r[4], re.IGNORECASE) is not None,
                                'source': r[5]}, ensure_ascii=False, separators=(',', ':')) + '\n')
        if not golden:
            f.write('\n')
    notes.append('golden-set.jsonl: %d cases' % len(golden))

    # Agent Card (A2A v1.0, https://a2a-protocol.org/latest/specification/). Always generated from the
    # agent's own files so it never drifts. It describes the agent's job, never its internal tools or skills.
    agent = _lines(os.path.join(path, 'AGENT.md'))
    prompt_path = os.path.join(path, 'PROMPT.md')
    prompt = _lines(prompt_path)
    changelog = _lines(os.path.join(path, 'CHANGELOG.md'))
    name = re.sub(r'^#\s+Agent:\s*', '', _first(agent, r'^#\s+Agent:') or '').strip()
    m = re.search(r'\*\*Role[^*]*\*\*[^:]*:\s*(.+)$', _first(prompt, r'\*\*Role') or '')
    description = m.group(1).strip() if m else ''
    m = re.match(r'^\|\s*(\d+\.\d+\.\d+)', _first(changelog, r'^\|\s*\d+\.\d+\.\d+\s*\|') or '')
    version = m.group(1) if m else '0.0.0'
    a2a = _first(agent, r'\*\*A2A:\*\*') or ''
    m = re.search(r'endpoint\s+(\S+)', a2a, re.IGNORECASE)
    endpoint = m.group(1) if m else ''
    m = re.search(r'binding\s+(\S+)', a2a, re.IGNORECASE)
    binding = m.group(1) if m else 'JSONRPC'
    m = re.search(r'auth\s+(\S+)', a2a, re.IGNORECASE)
    auth = m.group(1) if m else ''
    exposed = not _open(endpoint) and not re.search(r'\*\*A2A:\*\*\s*N/A', a2a, re.IGNORECASE)
    slug = re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')
    examples = []
    if os.path.isfile(prompt_path):
        examples = [r[1] for r in _table_rows(prompt_path, 'Examples')
                    if re.match(r'^P\d+$', r[0]) and len(r) > 1 and not _open(r[1])]

    skill = {'id': slug, 'name': name, 'description': description, 'tags': ['agent-standards']}
    if examples:
        skill['examples'] = examples
    interfaces = [{'url': endpoint, 'protocolBinding': binding, 'protocolVersion': '1.0'}] if exposed else []
    card = {'name': name, 'description': description, 'supportedInterfaces': interfaces, 'version': version,
            'capabilities': {'streaming': False, 'pushNotifications': False},
            'defaultInputModes': ['application/json'], 'defaultOutputModes': ['application/json'],
            'skills': [skill]}
    with open(os.path.join(build, 'agent-card.json'), 'w', encoding='utf-8') as f:
        json.dump(card, f, indent=2, ensure_ascii=False)
    notes.append('agent-card.json: version %s, %s' % (
        version, 'exposed at %s (%s)' % (endpoint, binding) if exposed else 'internal only (not exposed via A2A)'))
    if _open(name):
        notes.append('agent-card.json: name still TODO (AGENT.md heading)')
    if _open(description):
        notes.append('agent-card.json: description still TODO (PROMPT.md Role)')
    if exposed and not _open(auth):
        notes.append("agent-card.json: add the securitySchemes entry for '%s' before publishing it at "
                     "/.well-known/agent-card.json" % auth)

    return 'Built %s\n' % build + ''.join('- %s\n' % n for n in notes)


if __name__ == '__main__':
    if len(sys.argv) != 2:
        print('usage: python export_agent.py <agent folder>')
        sys.exit(2)
    print(run_export(sys.argv[1]), end='')
